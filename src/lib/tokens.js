// Token exports for a brand: CSS variables, Tailwind theme and W3C design tokens JSON.
import { config } from '../config.js';

export const kebab = (k) => k.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
export const cssVar = (k) => `--color-${kebab(k)}`;
const stack = (f) => f.split(',').map((s) => s.trim().replace(/^['"]|['"]$/g, ''));

export function toCss(b) {
  const lines = [`/* ${b.name} design tokens, generated by ${config.appName} */`, ':root {'];
  Object.entries(b.colors).forEach(([k, v]) => lines.push(`  ${cssVar(k)}: ${v};`));
  b.chart.forEach((c, i) => lines.push(`  --chart-${i + 1}: ${c};`));
  lines.push(`  --font-heading: ${b.fonts.heading};`, `  --font-body: ${b.fonts.body};`, `  --radius-base: ${b.radius};`, '}');
  return lines.join('\n');
}

export function toTailwind(b) {
  const colors = Object.entries(b.colors).map(([k, v]) => `        '${kebab(k)}': '${v}',`);
  const chart = b.chart.map((c, i) => `        'chart-${i + 1}': '${c}',`);
  const q = (arr) => `[${arr.map((s) => `'${s}'`).join(', ')}]`;
  return [
    `/** ${b.name}: Tailwind theme extension, generated by ${config.appName} */`,
    'export default {',
    '  theme: {',
    '    extend: {',
    '      colors: {',
    ...colors,
    ...chart,
    '      },',
    `      fontFamily: { heading: ${q(stack(b.fonts.heading))}, body: ${q(stack(b.fonts.body))} },`,
    `      borderRadius: { brand: '${b.radius}' },`,
    '    },',
    '  },',
    '};',
  ].join('\n');
}

/**
 * One brand as a Figma variables import file (DTCG 2025.10 colour objects).
 * In Figma: Variables → right-click a mode of the Brand collection → Import.
 */
export function toFigmaVariables(b) {
  const color = (hex) => {
    const h = hex.replace('#', '');
    const comp = [0, 2, 4].map((i) => Math.round((parseInt(h.slice(i, i + 2), 16) / 255) * 1e6) / 1e6);
    return { $type: 'color', $value: { colorSpace: 'srgb', components: comp, alpha: 1, hex: `#${h.toUpperCase()}` } };
  };
  const out = { color: {}, chart: {} };
  Object.entries(b.colors).forEach(([k, v]) => { out.color[kebab(k)] = color(v); });
  b.chart.forEach((c, i) => { out.chart[String(i + 1)] = color(c); });
  return JSON.stringify(out, null, 2);
}

export function toTokens(b) {
  const color = {};
  Object.entries(b.colors).forEach(([k, v]) => { color[kebab(k)] = { $type: 'color', $value: v }; });
  const chart = {};
  b.chart.forEach((c, i) => { chart[String(i + 1)] = { $type: 'color', $value: c }; });
  return JSON.stringify({
    $description: `${b.name} design tokens (W3C Design Tokens format), generated by ${config.appName}`,
    color,
    chart,
    font: { heading: { $type: 'fontFamily', $value: stack(b.fonts.heading) }, body: { $type: 'fontFamily', $value: stack(b.fonts.body) } },
    radius: { base: { $type: 'dimension', $value: b.radius } },
  }, null, 2);
}
